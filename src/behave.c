const animator_t *behaviours(int *count)
{
    static bool checked;
    const int n = (int)(sizeof table / sizeof table[0]);
    if (!checked) {
        for (int i = 1; i < n; i++) {
            if (table[i - 1].offset >= table[i].offset) {
                fprintf(stderr, "roc: behaviour table out of order at %04x\n", table[i].offset);
                abort();
            }
        }
        checked = true;
    }
    *count = n;
    return table;
}
