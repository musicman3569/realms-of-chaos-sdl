#!/usr/bin/env python3
"""Generate src/imagetab.h: the layout of the game's _Img (IMAGEstruct) sprite table.

Usage: python gen_imagetab.py analysis/ROC.tdinfo.txt extracted/rocimage.txt src/imagetab.h

IMAGEstruct is 141 arrays of SPRITE far* (1,059 pointers), one per sprite set: ArrowID[3],
BackStarID[3], BatID[4]... LOADOBJ loads "<name>.spr" into the array whose IMAGEDATA entry
matches a level's object list entry. The IMAGEDATA table is rocimage.txt in ROC.DAT (READITEM
0x47c): 141 records of a 9-byte name and a frame count, in the arrays' order. Its names are
mostly the field names without "ID", lower case, but not all (BossSpitID is "bosspit"), so the
names come from it and the layout from the debug info. The behaviours index these arrays
directly and sometimes past their end (DOBIRD's BirdID[4] is BirdpoopID[2]), so the port
keeps the same flat layout: IMG_<NAME> is the index of the set's first frame.
"""

import re
import sys


def main():
    td, image, out = sys.argv[1], sys.argv[2], sys.argv[3]
    fields = []
    for line in open(td):
        f = line.rstrip("\n").split("\t")
        if f[0] == "FIELD" and f[1] == "IMAGEstruct":
            m = re.search(r"\[(\d+)\]", f[4])
            fields.append((int(f[2]), f[3], int(m.group(1)) if m else 1))
    fields.sort()
    data = open(image, "rb").read()
    names = [(data[i:i + 9].split(b"\0")[0].decode(), data[i + 9]) for i in range(0, len(data), 10)]
    assert len(names) == len(fields), (len(names), len(fields))
    for (off, name, count), (file, frames) in zip(fields, names):
        assert count == frames, (name, count, file, frames)
    lines = [
        "/* Generated by tools/gen_imagetab.py from the Turbo Debugger info and rocimage.txt: the",
        " * layout of _Img (IMAGEstruct), the game's table of sprite frames. Don't edit. */",
        "#ifndef ROC_IMAGETAB_H",
        "#define ROC_IMAGETAB_H",
        "",
        "enum {",
    ]
    index = 0
    for off, name, count in fields:
        assert off == index * 4, (name, off, index)
        base = name[:-2] if name.endswith("ID") else name
        lines.append(f"    IMG_{base.upper()} = {index}, /* {name}[{count}] */")
        index += count
    lines += [f"    IMG_COUNT = {index},", f"    IMG_SETS = {len(fields)}", "};", ""]
    lines.append("/* Sprite set file names (without .spr) and frame slots, in table order. */")
    lines.append("static const struct { const char *name; int base, count; } image_sets[] = {")
    index = 0
    for (off, name, count), (file, frames) in zip(fields, names):
        lines.append(f'    {{"{file}", {index}, {count}}},')
        index += count
    lines += ["};", "", "#endif", ""]
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
